// Turns the brandbook logo SVGs into data for the <Logo> component (src/components/brand/Logo.tsx),
// so the sage halves of the O can be animated. Geometry is copied exactly, never redrawn.
// Run after the brandbook logos change: node scripts/build-logo.mjs
import { readFile, writeFile } from 'node:fs/promises'

const SOURCES = {
  wordmark: 'public/logos/POLUTONE_sage_light.svg',
  mark: 'public/brand/polutone-o.svg',
}
const SAGE = '#9EA99B'
const OUT = 'src/components/brand/logo-data.ts'

const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1]

/** Top-level shapes of the SVG: plain letters and the half-tone O groups. */
function parse(svg) {
  const viewBox = attr(svg.match(/<svg[^>]*>/)[0], 'viewBox')
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  const parts = []
  const re = /<g([^>]*)>([\s\S]*?)<\/g>|<path([^>]*)\/>/g
  for (const m of body.matchAll(re)) {
    if (m[3] !== undefined) {
      const tag = m[3]
      parts.push({ kind: 'path', d: attr(tag, 'd'), transform: attr(tag, 'transform') ?? null, sage: attr(tag, 'fill') === SAGE })
      continue
    }
    const rects = [...m[2].matchAll(/<rect([^>]*)\/>/g)].map(([, r]) => ({
      x: Number(attr(r, 'x')),
      y: Number(attr(r, 'y')),
      width: Number(attr(r, 'width')),
      height: Number(attr(r, 'height')),
    }))
    const halves = [...m[2].matchAll(/<path([^>]*)\/>/g)].map(([, p]) => ({
      d: attr(p, 'd'),
      sage: attr(p, 'fill') === SAGE,
      side: attr(p, 'clip-path').endsWith('L)') ? 'L' : 'R',
    }))
    if (rects.length !== 2 || halves.length !== 2) throw new Error('Unexpected O group in the logo SVG')
    parts.push({ kind: 'o', transform: attr(m[1], 'transform'), clips: { L: rects[0], R: rects[1] }, halves })
  }
  return { viewBox, parts }
}

const data = {}
for (const [name, file] of Object.entries(SOURCES)) data[name] = parse(await readFile(file, 'utf8'))

await writeFile(
  OUT,
  `// Generated by scripts/build-logo.mjs from the brandbook SVGs. Do not edit by hand.\n` +
    `import type { LogoData } from './Logo'\n\n` +
    Object.entries(data)
      .map(([name, value]) => `export const ${name}: LogoData = ${JSON.stringify(value, null, 2)}\n`)
      .join('\n'),
)
console.log(`Wrote ${OUT}: ${Object.entries(data).map(([n, v]) => `${n} ${v.parts.length} parts`).join(', ')}`)
